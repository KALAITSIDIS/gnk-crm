-- Read-only: it asserts, it never writes.
--
-- REGENERATED 2026-08-30 (audit REL-04). The previous pack had drifted ~25
-- migrations behind the schema: it checked 3 of 8 cron jobs, pinned a
-- 13-function grants table frozen before 0024, and its table list predated
